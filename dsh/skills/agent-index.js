/**
 * The always-visible skill index written into `AGENTS.md`.
 *
 * Progressive disclosure only works if the agent can see WHAT exists before it
 * decides what to load: every skill's name and its "use when" trigger, always in
 * context, with the body loaded on demand. DSH supplies that block itself; a
 * project that carries skills but no index depends on the runtime being DSH, and
 * in any other agent every skill is invisible — which is how a 5.9KB skill sat
 * in the repository for six weeks.
 *
 * The block is GENERATED, so it cannot drift: `npm run skills:catalog` writes it
 * and `--check` fails when it is stale. It is also BUDGETED, so the price of
 * always-on context is paid deliberately rather than by accretion.
 * @module dsh/skills/agent-index
 */

/** Hard ceiling for the generated block, in characters. Context is not free. */
export const SKILL_INDEX_BUDGET = 6000;

/** Longest single trigger line, so one verbose description cannot eat the budget. */
export const TRIGGER_MAX = 130;

export const INDEX_START = '<!-- SKILL-INDEX:START -->';
export const INDEX_END = '<!-- SKILL-INDEX:END -->';

/**
 * One line of routing text from a skill's description.
 * @param {string} description
 * @returns {string}
 */
export function triggerOf(description) {
  const text = String(description).replace(/\s+/gu, ' ').trim();
  if (text.length <= TRIGGER_MAX) return text;
  const cut = text.slice(0, TRIGGER_MAX);
  const space = cut.lastIndexOf(' ');
  return `${(space > 40 ? cut.slice(0, space) : cut).replace(/[,;:.\s]+$/u, '')}…`;
}

/**
 * Build the block body (without the marker lines).
 * @param {Array<{name: string, description: string}>} skills
 * @returns {string}
 */
export function buildIndexBody(skills) {
  const rows = [...skills]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((skill) => `- \`${skill.name}\` — ${triggerOf(skill.description)}`);
  return [
    `**${rows.length} skills.** Read the trigger, then load only the body you need.`,
    '',
    ...rows,
  ].join('\n');
}

/**
 * The full marked block, ready to replace in `AGENTS.md`.
 * @param {Array<{name: string, description: string}>} skills
 * @returns {string}
 */
export function buildIndexBlock(skills) {
  return [
    INDEX_START,
    '<!-- generated by npm run skills:catalog — do not edit by hand -->',
    buildIndexBody(skills),
    INDEX_END,
  ].join('\n');
}

/**
 * Replace (or append) the block in a document.
 * @param {string} document
 * @param {string} block
 * @returns {string}
 */
export function applyIndexBlock(document, block) {
  const start = document.indexOf(INDEX_START);
  const end = document.indexOf(INDEX_END);
  if (start !== -1 && end !== -1 && end > start) {
    return `${document.slice(0, start)}${block}${document.slice(end + INDEX_END.length)}`;
  }
  const trimmed = document.replace(/\s+$/u, '');
  return `${trimmed}\n\n## Skill index (generated)\n\n${block}\n`;
}

/**
 * The longest trigger lines, so an over-budget index has an obvious target.
 * @param {Array<{name: string, description: string}>} skills
 * @param {number} count
 */
export function heaviest(skills, count = 5) {
  return [...skills]
    .map((skill) => ({ name: skill.name, length: triggerOf(skill.description).length }))
    .sort((a, b) => b.length - a.length)
    .slice(0, count);
}
